"""Only server-owned, allowlisted complete aggregations may use the larger cap."""
from improved.compiler import QueryPlan, PlanRejected
from improved.guard import SQLGuard

MAX_ANALYSIS_GROUPS = 10000


def validate_analysis_plan(plan, compiler):
    config = compiler.rules.get('analysis', {})
    if plan.analysis not in {'segments','volume_value'} or plan.comparison_filters is None:
        raise PlanRejected('贡献分解需要已批准的类型和完整两期条件')
    time_fields = set(config.get('time_fields', []))
    aliases = config.get('equivalent_fields', {})
    def scope(filters):
        return sorted((aliases.get(f.field,f.field), f.op, repr(f.value)) for f in filters if f.field not in time_fields)
    if scope(plan.filters) != scope(plan.comparison_filters):
        raise PlanRejected('贡献分解的两期非时间筛选必须相同，不能混用不同人群')
    if len(plan.metrics) != 1:
        raise PlanRejected('每次贡献分解只支持一个目标指标')
    if plan.analysis == 'segments':
        if plan.metrics[0] not in config.get('additive_metrics', []):
            raise PlanRejected('该指标不是已批准的可加指标，不能直接汇总分组贡献')
        if len(plan.dimensions) != 1 or plan.dimensions[0] not in config.get('partition_dimensions', []):
            raise PlanRejected('请选择一个已批准的互斥分组维度')
    elif plan.metrics != [config.get('volume_value', {}).get('revenue')] or plan.dimensions:
        raise PlanRejected('订单数与客单价分解仅支持已注册销售额的整体两期比较')


def build_analysis_queries(plan, compiler):
    validate_analysis_plan(plan, compiler)
    config = compiler.rules['analysis']
    queries = []
    def add(name, dimensions, metrics, comparison, complete=False):
        working = plan.model_copy(update={'analysis': None, 'dimensions': dimensions, 'metrics': metrics, 'order_by': None, 'limit': 1 if not dimensions else 200})
        compiled = compiler.compile(working, comparison=comparison)
        sql = compiled.sql
        if complete:
            # Input is freshly generated by our compiler, never arbitrary model SQL.
            sql = sql.rsplit(' LIMIT ',1)[0] + f' LIMIT {MAX_ANALYSIS_GROUPS+1}'
        SQLGuard(compiler.policy['tables'], max_rows=MAX_ANALYSIS_GROUPS+1).validate(sql)
        queries.append({'name':name, 'sql':sql, 'params':compiled.params})
    if plan.analysis == 'segments':
        for baseline, prefix in [(False,'current'),(True,'previous')]:
            add(prefix+'_groups',plan.dimensions,plan.metrics,baseline,complete=True)
            add(prefix+'_total',[],plan.metrics,baseline)
    else:
        recipe = config['volume_value']
        for baseline, prefix in [(False,'current'),(True,'previous')]:
            add(prefix+'_total',[],[recipe['revenue'],recipe['orders']],baseline)
    return queries
